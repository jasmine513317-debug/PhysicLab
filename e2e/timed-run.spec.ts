import { expect, test } from '@playwright/test'

test('repeats an exact stop after a parameter edit and reports fixed-step rounding', async ({page}) => {
  await page.goto('/lab?template=friction')
  await page.getByRole('button', {name:'定时运行', exact:true}).click()
  const input = page.getByRole('spinbutton', {name:'目标模拟时间（秒）'})
  const start = page.getByRole('button', {name:'开始定时运行', exact:true})
  const clock = page.getByLabel('模拟时间', {exact:true})
  await input.fill('0')
  await expect(start).toBeDisabled()
  await input.fill('0.707')
  await expect(page.getByText('按 60 Hz 步长，将在 0.700 秒暂停。')).toBeVisible()
  await page.getByRole('combobox', {name:'播放速度'}).selectOption('4')
  await start.click()
  await expect(clock).toHaveText('0.700 s')
  await expect(page.getByRole('button', {name:'从头定时运行'})).toBeEnabled()
  await page.getByRole('button', {name:'设为基准'}).click()
  const friction = page.getByRole('spinbutton', {name:'摩擦系数',exact:true})
  await friction.fill('0.9')
  await friction.press('Enter')
  await expect(clock).toHaveText('0.000 s')
  await expect(input).toHaveValue('0.707')
  await start.click()
  await expect(clock).toHaveText('0.700 s')
  await expect(page.getByRole('button', {name:'从头定时运行'})).toBeEnabled()
})
