import { expect,test } from '@playwright/test'

test('opens the J2000 preset, toggles reference layers and preserves the simulated state when changing the camera',async({page})=>{
  await page.goto('/lab?new=1&choose=1')
  await page.getByRole('region',{name:'基础模型与实验模板'})
    .locator('summary').filter({hasText:'天体物理'}).click()
  await page.getByRole('link',{name:'太阳系 · J2000',exact:true}).click()
  const canvas=page.getByLabel('三维实验画布'),grid=page.getByRole('button',{name:'坐标网格'})
  const axes=page.getByRole('button',{name:'坐标轴',exact:true})
  const time=page.getByLabel('三维模拟时间')
  await expect(canvas).toBeVisible()
  await expect(grid).toHaveAttribute('aria-pressed','true')
  await page.getByRole('button',{name:'属性',exact:true}).click()
  const bodies=page.getByLabel('三维对象')
  await expect(bodies.locator('option')).toHaveCount(10)
  await bodies.selectOption({label:'地球'})
  const x=page.getByRole('spinbutton',{name:'位置 (m) X',exact:true})
  const before=await x.inputValue()
  const bounds=(await canvas.boundingBox())!
  await page.mouse.move(bounds.x+80,bounds.y+120);await page.mouse.down()
  await page.mouse.move(bounds.x+155,bounds.y+170,{steps:5});await page.mouse.up()
  await page.getByRole('button',{name:'放近三维视角'}).click()
  await expect(x).toHaveValue(before)
  await expect(time).toHaveText('0.000 s')
  await page.getByRole('button',{name:'运行',exact:true}).click()
  await expect(grid).toHaveAttribute('aria-pressed','false')
  await expect(axes).toHaveAttribute('aria-pressed','false')
  await expect(time).not.toHaveText('0.000 s')
  await page.getByRole('button',{name:'暂停',exact:true}).click()
  await expect(grid).toHaveAttribute('aria-pressed','true')
  await grid.click()
  await expect(grid).toHaveAttribute('aria-pressed','false')
  await expect(axes).toHaveAttribute('aria-pressed','true')
  await page.getByRole('button',{name:'保存三维实验'}).click()
  await expect(page.getByText('已保存三维场景、模拟时间和轨迹。')).toBeVisible()
  const saved=await time.innerText()
  await page.reload()
  await expect(time).toHaveText(saved)
  await expect(grid).toHaveAttribute('aria-pressed','false')
})

test('edits a Kerr model, reloads it from the library, and plays the calibrated remnant',async({page})=>{
  await page.goto('/lab?new=1&space=astronomy')
  const assets=page.getByLabel('添加天体模型')
  await assets.selectOption('blackHole')
  const spin=page.getByRole('spinbutton',{name:'无量纲自旋 χ'})
  const horizon=page.getByText(/外视界 .*最内稳定圆轨道/)
  const originally=await horizon.innerText()
  await spin.fill('0.7')
  await spin.press('Enter')
  expect(await horizon.innerText()).not.toBe(originally)
  await page.getByRole('button',{name:'保存到我的天体模型'}).click()
  const saved=assets.locator('optgroup[label="我的天体模型"] option')
  await expect(saved).toHaveCount(1)
  const assetId=await saved.getAttribute('value')
  await page.reload()
  await assets.selectOption(assetId!)
  await expect(spin).toHaveValue('0.7')
  await page.getByLabel('加载三维模板').selectOption('ringdown')
  await expect(page.getByRole('img',{name:'计算的黑洞振铃波形'})).toBeVisible()
  await page.getByRole('button',{name:'运行',exact:true}).click()
  await expect(page.getByText(/已到达计算边界/)).toBeVisible()
})

