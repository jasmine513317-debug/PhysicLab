import { expect, test } from '@playwright/test'

test('updates the dipole probe and renders each static field layer',async({page})=>{
  await page.goto('/lab?domain=electromagnetism')
  const readout=page.getByRole('region',{name:'探针读数'})
  const canvas=page.getByLabel('电场画布')
  await expect(readout).toContainText('39.945 N/C')
  await expect(readout).toContainText('0 V')
  const pixels=()=>canvas.evaluate((element:HTMLCanvasElement)=>element.toDataURL())
  for(const name of ['电场线','电场矢量','电势热力图','等势线']) {
    const before=await pixels()
    await page.getByRole('checkbox',{name,exact:true}).click()
    await expect.poll(pixels).not.toBe(before)
  }
  const probe=page.getByRole('spinbutton',{name:'探针 X m'})
  await probe.fill('-1.5')
  await probe.press('Enter')
  await expect(readout.getByRole('status')).toContainText('点电荷的奇点')
  await page.setViewportSize({width:375,height:812})
  await expect(canvas).toBeVisible()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBe(375)
})

test('edits, saves, reopens, and imports a static experiment from the shared library',async({page})=>{
  await page.goto('/experiments')
  await page.getByRole('region',{name:'实验模板'}).getByRole('link',{name:'等势线',exact:true}).click()
  await expect(page.getByRole('checkbox',{name:'电势热力图'})).toBeChecked()
  const title=page.getByLabel('静电实验名称')
  await title.fill('同号电势实验')
  await title.press('Enter')
  const amount=page.getByRole('spinbutton',{name:'电荷量 nC'})
  await amount.fill('10')
  await amount.press('Enter')
  const canvas=page.getByLabel('电场画布')
  await page.getByRole('button',{name:'负电荷',exact:true}).click()
  await canvas.click({position:{x:100,y:100}})
  await expect(amount).toHaveValue('-5')
  const x=page.getByRole('spinbutton',{name:'电荷 X m'})
  const before=await x.inputValue()
  const frame=(await canvas.boundingBox())!
  await page.mouse.move(frame.x+100,frame.y+100)
  await page.mouse.down()
  await page.mouse.move(frame.x+150,frame.y+125,{steps:5})
  await page.mouse.up()
  await expect(x).not.toHaveValue(before)
  await page.getByRole('button',{name:'删除电荷'}).click()
  await expect(page.getByRole('combobox',{name:'选择电荷'}).getByRole('option',{name:/电荷 1 · 10 nC/})).toHaveCount(1)
  const domains=page.getByRole('navigation',{name:'实验领域'})
  await domains.getByRole('link',{name:'经典力学'}).click()
  await domains.getByRole('link',{name:'电磁学'}).click()
  await expect(title).toHaveValue('同号电势实验')
  await page.getByRole('button',{name:'保存实验',exact:true}).click()
  await expect(page.getByRole('button',{name:'已保存',exact:true})).toBeVisible()
  await page.reload()
  await expect(title).toHaveValue('同号电势实验')
  await expect(amount).toHaveValue('10')
  const download=page.waitForEvent('download')
  await page.getByRole('button',{name:'导出场景 JSON'}).click()
  const file=await download
  await page.goto('/experiments')
  await page.getByLabel('导入实验 JSON').setInputFiles(await file.path())
  await expect(page.getByRole('link',{name:'预览：同号电势实验'})).toHaveCount(2)
  await page.getByRole('link',{name:'预览：同号电势实验'}).first().click()
  await expect(amount).toHaveValue('10')
})
