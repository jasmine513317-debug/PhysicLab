import { expect, test } from '@playwright/test'

test('undo restores a deleted body and its spring, and a new edit replaces the redo branch', async ({page})=>{
  await page.goto('/lab?template=spring')
  const canvas=page.getByLabel('物理场景')
  const objects=page.getByRole('combobox',{name:'当前物体'})
  const undo=page.getByRole('button',{name:'撤销',exact:true})
  const redo=page.getByRole('button',{name:'重做',exact:true})
  const spring=objects.locator('option',{hasText:'弹簧 1'})
  const body=objects.locator('option',{hasText:'振动物体'})
  await expect(undo).toBeDisabled()
  await page.getByRole('button',{name:'单步运行'}).click()
  await expect(undo).toBeDisabled()
  await canvas.press('Delete')
  await expect(body).toHaveCount(0)
  await expect(spring).toHaveCount(0)
  await canvas.press('Control+z')
  await expect(body).toHaveCount(1)
  await expect(spring).toHaveCount(1)
  await expect(objects.locator('option:checked')).toHaveText('振动物体')
  await canvas.press('Control+Shift+z')
  await expect(spring).toHaveCount(0)
  await undo.click()
  const mass=page.getByRole('spinbutton',{name:'质量',exact:true})
  await mass.fill('3')
  await mass.press('Enter')
  await expect(redo).toBeDisabled()
  await undo.click()
  await expect(mass).toHaveValue('1')
})

test('a drag creates one edit regardless of pointer movement count',async({page})=>{
  await page.goto('/lab?new=1')
  const tools=page.getByRole('complementary',{name:'场景工具'})
  const canvas=page.getByLabel('物理场景')
  await tools.getByRole('button',{name:'圆形',exact:true}).click()
  await canvas.click({position:{x:140,y:120}})
  await tools.getByRole('button',{name:'选择',exact:true}).click()
  const x=page.getByRole('spinbutton',{name:'X 坐标'})
  const initialX=await x.inputValue()
  const bounds=(await canvas.boundingBox())!
  await page.mouse.move(bounds.x+140,bounds.y+120)
  await page.mouse.down()
  await page.mouse.move(bounds.x+180,bounds.y+130,{steps:12})
  await page.mouse.up()
  await expect(x).not.toHaveValue(initialX)
  await canvas.press('Control+z')
  await expect(x).toHaveValue(initialX)
  await canvas.press('Control+z')
  await expect(page.getByText('当前场景为空')).toBeVisible()
  await canvas.press('Control+y')
  await expect(x).toHaveValue(initialX)
})

test('committed notes follow edit history and preserve native typing shortcuts', async ({page})=>{
  await page.goto('/lab?new=1')
  const notes=page.getByRole('textbox',{name:'实验笔记'})
  await notes.fill('第一次观察')
  await notes.press('Tab')
  await page.getByRole('button',{name:'撤销',exact:true}).click()
  await expect(notes).toHaveValue('')
  await page.getByRole('button',{name:'重做',exact:true}).click()
  await expect(notes).toHaveValue('第一次观察')
  await notes.fill('尚未提交')
  await notes.press('Control+z')
  await expect(page.getByRole('button',{name:'重做',exact:true})).toBeDisabled()
})
