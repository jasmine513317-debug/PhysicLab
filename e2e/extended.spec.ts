import { readFile } from 'node:fs/promises'
import { expect, test } from '@playwright/test'
import { openAnalysis } from './helpers'

test('shows spring theory and measures the finite-amplitude pendulum period',async({page})=>{
  await page.goto('/lab?template=spring')
  await openAnalysis(page)
  await page.getByRole('button',{name:'对比',exact:true}).click()
  await expect(page.getByRole('row',{name:/振动周期/})).toContainText('0.628 s')
  await page.getByRole('button',{name:'打开实验菜单'}).click()
  await page.locator('#app-content').getByRole('link',{name:'单摆',exact:true}).click()
  await page.getByLabel('扩展实验播放速度').selectOption('8')
  await expect(page.getByLabel('扩展实验画布')).toBeVisible()
  await page.getByRole('button',{name:'运行',exact:true}).click()
  const period=page.getByRole('region',{name:'测量读数'}).locator('dd').first()
  await expect(period).toHaveText(/^2\.0\d+ s$/)
  await page.getByRole('button',{name:'暂停',exact:true}).click()
  await page.getByRole('button',{name:'重置实验'}).click()
  await expect(period).toHaveText('— s')
})

test('switches RC phases, exports current, and reopens a saved experiment',async({page})=>{
  await page.goto('/lab?domain=electromagnetism&extension=rc')
  await page.getByRole('button',{name:'单步推进'}).click()
  const readout=page.getByRole('region',{name:'测量读数'}).locator('dd')
  const voltage=await readout.first().innerText()
  await page.getByRole('button',{name:'切换放电'}).click()
  await expect(readout.first()).toHaveText(voltage)
  await expect(readout.nth(1)).toHaveText(/^-/)
  const waiting=page.waitForEvent('download')
  await page.getByRole('button',{name:'导出数据 CSV'}).click()
  const csv=await readFile(await (await waiting).path(),'utf8')
  expect(csv).toContain('capacitor_V,current_A,source_V,energy_J')
  await page.getByRole('button',{name:'保存实验'}).click()
  await expect(page.getByRole('button',{name:'已保存'})).toBeVisible()
  await page.goto('/experiments')
  await page.getByRole('link',{name:'预览：RC 电路暂态'}).click()
  await expect(page.getByLabel('扩展实验名称')).toHaveValue('RC 电路暂态')
  const json=page.waitForEvent('download')
  await page.getByRole('button',{name:'导出场景 JSON'}).click()
  const file=await json
  await page.goto('/experiments')
  await page.getByLabel('导入实验 JSON').setInputFiles(await file.path())
  await expect(page.getByRole('link',{name:'预览：RC 电路暂态'})).toHaveCount(2)
})

test('runs a magnetic particle and classifies escape speed presets',async({page})=>{
  await page.goto('/lab?domain=electromagnetism&extension=particle')
  await page.setViewportSize({width:375,height:812})
  await expect(page.getByLabel('扩展实验画布')).toBeVisible()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBe(375)
  await page.getByRole('button',{name:'单步推进'}).click()
  await expect(page.getByRole('region',{name:'测量读数'})).toContainText('4.5 J')
  await expect(page.getByLabel('扩展实验时间')).not.toHaveText('0 s')
  await page.goto('/lab?domain=astrophysics&preset=escape')
  const panel=page.getByRole('region',{name:'逃逸速度'})
  await expect(panel).toContainText('束缚轨道')
  await panel.getByRole('button',{name:'1× 逃逸速度',exact:true}).click()
  await expect(panel).toContainText('临界抛物线')
  await panel.getByRole('button',{name:'1.2× 逃逸速度',exact:true}).click()
  await expect(panel).toContainText('逃逸轨道')
})
