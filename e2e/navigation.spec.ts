import { expect, test } from '@playwright/test'

test('opens templates and recent experiments from the sidebar', async ({ page }) => {
  await page.goto('/lab?template=fall')
  await page.getByRole('button', { name: '保存实验' }).click()
  await expect(page.getByRole('button', { name: '已保存', exact: true })).toBeVisible()
  await page.goto('/')
  await expect(page.getByRole('heading', { name: /先搭一个世界/ })).toBeVisible()
  await expect(page.locator('.hero-simulation')).toHaveCount(0)
  await expect(page.getByRole('link', { name: '打开斜抛运动实验' })).toBeVisible()
  await expect(page.locator('.hp-row')).toHaveCount(3)
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(1440)
  await expect(
    page.getByRole('region', { name: '最近实验' })
      .getByRole('link', { name: /自由落体/ })
  ).toBeVisible()
  await expect(page.locator('#app-content').getByRole('heading', { name: '实验模板', exact: true })).toHaveCount(0)
  await expect(page.getByRole('region', { name: '实验模板' })).toBeVisible()
  await page.getByRole('region', { name: '实验模板' })
    .getByRole('link', { name: '弹簧振子', exact: true }).click()
  await expect(page.getByLabel('实验标题')).toHaveValue('弹簧振子')
  await page.goto('/experiments')
  await expect(page.getByRole('heading', { name: '从模板开始' })).toHaveCount(0)
  await expect(page.getByRole('region', { name: '实验模板' })).toBeVisible()
})

test('opens the mobile sidebar drawer and navigates without overflow', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
  await expect(page.locator('#app-sidebar')).not.toBeVisible()
  await page.getByRole('button', { name: '打开侧边栏' }).click()
  await expect(page.locator('#app-sidebar')).toBeVisible()
  await expect(page.getByRole('region', { name: '实验模板' })).toBeVisible()
  await page.getByRole('region', { name: '实验模板' })
    .getByRole('link', { name: '自由落体', exact: true }).click()
  await expect(page.getByLabel('实验标题')).toHaveValue('自由落体')
  await expect(page.locator('#app-sidebar')).not.toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
})

test('keeps Studio navigation and every domain available in the compact rail', async ({ page }) => {
  await page.setViewportSize({ width: 1024, height: 900 })
  await page.goto('/')
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(1024)
  await page.getByRole('navigation', { name: '主导航' })
    .getByRole('link', { name: '几何工作室', exact: true }).click()
  await expect(page.getByLabel('二维几何画布')).toBeVisible()
  await page.goto('/lab?domain=astrophysics')
  await expect(page.getByLabel('轨道画布')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(1024)
})
