test('generates and rotates a surface, then exports a mesh on a narrow screen',async({page})=>{
  await page.setViewportSize({width:375,height:812})
  await page.goto('/geometry')
  await page.getByRole('button',{name:'三维曲面'}).click()
  const canvas=page.getByLabel('三维曲面画布')
  await expect(canvas).toBeVisible()
  const pixels=()=>canvas.evaluate((node:HTMLCanvasElement)=>node.toDataURL())
  const initial=await pixels(),frame=(await canvas.boundingBox())!
  await page.mouse.move(frame.x+frame.width*.57,frame.y+frame.height*.42)
  await page.mouse.down()
  await page.mouse.move(frame.x+frame.width*.71,frame.y+frame.height*.49,{steps:6})
  await page.mouse.up()
  await expect.poll(pixels).not.toBe(initial)
  const rotated=await pixels()
  await canvas.press('ArrowRight')
  await expect.poll(pixels).not.toBe(rotated)
  await expect(page.getByText(/1152 个三角面 · 625 个顶点/)).toBeVisible()
  const download=page.waitForEvent('download')
  await page.getByRole('button',{name:'导出 OBJ'}).click()
  expect((await download).suggestedFilename()).toBe('未命名几何.obj')
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBe(375)
  const fit=await page.getByRole('navigation',{name:'几何模式'}).evaluate(nav=>{
    const frame=nav.getBoundingClientRect()
    return [...nav.querySelectorAll('button')].every(button=>button.getBoundingClientRect().right<=frame.right)
  })
  expect(fit).toBe(true)
})
