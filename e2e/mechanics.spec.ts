import { readFile } from 'node:fs/promises'
import { expect, test } from '@playwright/test'
import { openAnalysis, openProperties } from './helpers'

test('plots system and individual momentum, exports samples, and reopens momentum in replay',async({page})=>{
  await page.goto('/lab?template=collision')
  await page.getByLabel('播放速度').selectOption('4')
  await openAnalysis(page)
  await page.getByRole('button',{name:'动量',exact:true}).click()
  await page.getByRole('button',{name:'运行',exact:true}).click()
  await expect.poll(async()=>parseFloat(await page.getByLabel('模拟时间',{exact:true}).innerText())).toBeGreaterThan(1.25)
  await page.getByRole('button',{name:'暂停',exact:true}).click()
  const subject=page.getByLabel('分析对象')
  const summary=page.getByLabel('动量变化摘要')
  await expect(subject).toHaveValue('')
  await expect(summary).toContainText(/Δpₓ\s*-?0\.000 kg·m\/s/)
  await expect(summary).toContainText(/Δ动能\s*-?0\.000 J/)
  await subject.selectOption({label:'运动圆盘'})
  await expect(summary).toContainText(/Δpₓ\s*-4\.000 kg·m\/s/)
  const waitDownload=page.waitForEvent('download')
  await page.getByRole('button',{name:'导出动量 CSV'}).click()
  const download=await waitDownload
  const data=await readFile(await download.path(),'utf8')
  expect(data).toContain('time_s,px_kg_m_per_s,py_kg_m_per_s,kinetic_J')
  expect(data).toContain('0.000000,4.000000,0.000000,8.000000')
  await page.getByRole('button',{name:'历史回放'}).click()
  await subject.selectOption({label:'全体动态物体'})
  await expect(summary).toContainText(/Δpₓ\s*-?0\.000 kg·m\/s/)
  await page.setViewportSize({width:375,height:812})
  await expect(summary).toBeVisible()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBe(375)
})

test('shows the free-fall reference and runs the curve-track template from the sidebar',async({page})=>{
  await page.goto('/lab?template=fall')
  for(let i=0;i<8;i++)await page.getByRole('button',{name:'单步运行'}).click()
  await openAnalysis(page)
  await page.getByRole('button',{name:'对比',exact:true}).click()
  await expect(page.getByRole('columnheader',{name:'理论参考值'})).toBeVisible()
  await expect(page.getByRole('row',{name:/竖直速度/})).toContainText('-1.308 m/s')
  await page.goto('/experiments')
  await page.getByRole('region',{name:'实验模板'}).getByRole('link',{name:'曲线轨道',exact:true}).click()
  await expect(page.getByLabel('实验标题')).toHaveValue('曲线轨道')
  await openProperties(page)
  await page.getByLabel('当前物体').selectOption({label:'抛物线轨道'})
  await expect(page.getByText(/静态碰撞轨道 · 25 个顶点/)).toBeVisible()
  await page.getByRole('button',{name:'单步运行'}).click()
  await expect(page.getByLabel('模拟时间',{exact:true})).toHaveText('0.017 s')
})
